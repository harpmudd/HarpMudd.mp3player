#!/usr/bin/env python3
"""Checks the corroborating re-read against the first parse.

read_track_head() accuses the SD card of a damaged directory entry when APF's
file size exceeds the file's own Xing/VBRI BYTES field by more than 25%, and
it also replaces slot_size with its own figure. Because that was decided from a
single unvalidated read, it now re-reads and only acts if the second read
agrees -- vbr_bytes_again() against vbr_frame_count().

Two properties matter, and they pull in opposite directions:

  AGREE    on a good read the two must return the SAME value, or a genuine
           corruption warning would be silently suppressed.
  DISAGREE on a bad read they must differ, or the guard does nothing.

Both are tested. The second is the negative control: the stubbed read is fed
deliberately corrupted bytes, and the suite fails if the guard still agrees.

Both functions are EXTRACTED from fw/player.c, so what is tested is what ships,
and they run under tools/rv32sim.py.

    python tools/host/vbr_check.py
"""
import io
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
CARD = 'E:/Assets/mp3player/common'
MAXF = 8
HEAD = 4096


def extract(src, sig):
    i = src.index(sig)
    j = src.index('{', i)
    depth = 0
    for k in range(j, len(src)):
        if src[k] == '{':
            depth += 1
        elif src[k] == '}':
            depth -= 1
            if depth == 0:
                return src[i:k + 1]
    raise SystemExit('unbalanced braces extracting %s' % sig)


def id3_len(b):
    if b[:3] != b'ID3':
        return 0
    return 10 + ((b[6] << 21) | (b[7] << 14) | (b[8] << 7) | b[9]) \
             + (10 if (b[5] & 0x10) else 0)


def gather():
    """Real file heads, positioned exactly as the ring would be."""
    out = []
    if os.path.isdir(CARD):
        for dp, _, fns in os.walk(CARD):
            for fn in sorted(fns):
                if not fn.lower().endswith('.mp3'):
                    continue
                p = os.path.join(dp, fn)
                raw = open(p, 'rb').read(HEAD + 65536)
                skip = id3_len(raw)
                head = raw[skip:skip + HEAD]
                if len(head) < HEAD:
                    continue
                # only files that actually carry the field under test
                if b'Xing' not in head[:2048] and b'Info' not in head[:2048] \
                        and b'VBRI' not in head[:2048]:
                    continue
                out.append((fn, head))
                if len(out) >= MAXF:
                    return out
    return out


SYNTH = []


def synth():
    """Shapes the card may not happen to contain."""
    def frame(tag, flags, frames, nbytes, at=36):
        b = bytearray(HEAD)
        b[0:4] = b'\xff\xfb\x90\x00'
        b[at:at + 4] = tag
        b[at + 4:at + 8] = flags.to_bytes(4, 'big')
        b[at + 8:at + 12] = frames.to_bytes(4, 'big')
        b[at + 12:at + 16] = nbytes.to_bytes(4, 'big')
        return bytes(b)

    def vbri(nbytes, frames, at=36):
        b = bytearray(HEAD)
        b[0:4] = b'\xff\xfb\x90\x00'
        b[at:at + 4] = b'VBRI'
        b[at + 10:at + 14] = nbytes.to_bytes(4, 'big')
        b[at + 14:at + 18] = frames.to_bytes(4, 'big')
        return bytes(b)

    SYNTH.append(('Xing FRAMES+BYTES', frame(b'Xing', 3, 9000, 5_000_000)))
    SYNTH.append(('Info FRAMES+BYTES', frame(b'Info', 3, 9000, 11_235_069)))
    SYNTH.append(('Xing FRAMES only', frame(b'Xing', 1, 9000, 0)))
    SYNTH.append(('Xing all flags', frame(b'Xing', 15, 9000, 7_777_777)))
    SYNTH.append(('VBRI', vbri(3_000_000, 4000)))
    return SYNTH


def build(cases, corrupt):
    pc = io.open(os.path.join(ROOT, 'fw', 'player.c'),
                 encoding='utf-8', errors='replace').read()
    first = extract(pc, 'static uint32_t vbr_frame_count')
    again = extract(pc, 'static uint32_t vbr_bytes_again')

    gen = os.path.join(HERE, 'vbr_gen.c')
    with io.open(gen, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* GENERATED by vbr_check.py from fw/player.c. */\n')
        f.write('#include "hostio.h"\n\n')
        f.write('#define TAG_SIZE 4096u\n')
        f.write('#define TAG_OFF  0u\n')
        f.write('#define HEAD     %du\n\n' % HEAD)
        f.write('static unsigned char ring[HEAD];\n')
        f.write('static unsigned char tagbuf_[HEAD];\n')
        f.write('static unsigned char * const tagbuf = tagbuf_;\n')
        f.write('static unsigned int ring_fill;\n')
        f.write('static uint32_t track_bytes, track_frames, track_vbr_method;\n')
        f.write('static char      track_encoder[10];\n')
        f.write('static unsigned char xing_toc[100];\n')
        f.write('static unsigned char xing_toc_ok;\n')
        f.write('static unsigned char CORRUPT;\n\n')
        # The read under test. A GOOD read hands back the same bytes the ring
        # holds; a BAD one hands back something else, which is the whole point.
        f.write('static int target_read(uint32_t at, uint32_t dst, uint32_t len)\n')
        f.write('{\n    (void)at; (void)dst;\n')
        f.write('    for (uint32_t i = 0; i < len && i < HEAD; i++)\n')
        f.write('        tagbuf_[i] = CORRUPT ? (unsigned char)(ring[i] ^ 0x5Au)\n')
        f.write('                             : ring[i];\n')
        f.write('    return 1;\n}\n\n')
        f.write(first + '\n\n')
        f.write(again + '\n\n')

        for ci, (_, head) in enumerate(cases):
            f.write('static const unsigned char H%d[HEAD] = {%s};\n'
                    % (ci, ','.join(str(b) for b in head)))

        f.write('\nint main(void)\n{\n')
        f.write('    CORRUPT = %du;\n' % (1 if corrupt else 0))
        for ci, _ in enumerate(cases):
            f.write('    {\n')
            f.write('        for (uint32_t k = 0; k < HEAD; k++) ring[k] = H%d[k];\n' % ci)
            f.write('        ring_fill = HEAD;\n')
            f.write('        track_bytes = 0; xing_toc_ok = 0;\n')
            f.write('        (void)vbr_frame_count();\n')
            f.write('        uint32_t a = track_bytes;\n')
            f.write('        uint32_t b = vbr_bytes_again(0);\n')
            f.write('        hputu(a); hputc(32); hputu(b); hnl();\n')
            f.write('    }\n')
        f.write('    return 0;\n}\n')

    gcc = os.path.join(ROOT, 'toolchain',
                       'xpack-riscv-none-elf-gcc-15.2.0-1', 'bin',
                       'riscv-none-elf-gcc.exe')
    elf = os.path.join(HERE, 'vbr.elf')
    r = subprocess.run([gcc, '-march=rv32im', '-mabi=ilp32', '-mno-relax',
                        '-O2', '-ffreestanding', '-nostdlib', '-nostartfiles',
                        '-T', os.path.join(HERE, 'link.ld'), '-o', elf,
                        os.path.join(HERE, 'start.S'), gen, '-lgcc'],
                       capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[:2000])
        raise SystemExit(2)
    out = subprocess.run([sys.executable,
                          os.path.join(ROOT, 'tools', 'rv32sim.py'), elf],
                         capture_output=True, text=True)
    if out.returncode:
        print(out.stderr[:2000])
        raise SystemExit(2)
    return [tuple(int(x) for x in l.split())
            for l in out.stdout.splitlines() if l.strip()]


def main():
    cases = gather() + synth()
    if not cases:
        print('no cases -- card absent and synth empty')
        return 2
    print('%d cases (%d real from the card, %d synthetic)'
          % (len(cases), len(cases) - len(SYNTH), len(SYNTH)))
    print()

    ok = True
    good_rows = build(cases, False)

    # A file with no BYTES field leaves track_bytes at 0, so read_track_head's
    # `if (track_bytes && slot_size)` never runs and vbr_bytes_again is never
    # called. Those cases are NOT agreement and NOT failure -- the guard is
    # unreachable. Counting them either way is how a test starts reporting on
    # something other than the property it names.
    live = [i for i, (a, _) in enumerate(good_rows) if a != 0]
    dead = [i for i, (a, _) in enumerate(good_rows) if a == 0]

    print('GOOD read -- the two parses must AGREE')
    for i in live:
        name = cases[i][0]
        a, b = good_rows[i]
        good = (a == b)
        if not good:
            ok = False
        print('  %-5s %-40s first=%-11d again=%d'
              % ('ok' if good else 'FAIL', name[:40], a, b))
    for i in dead:
        print('  %-5s %-40s no BYTES field: guard unreachable'
              % ('n/a', cases[i][0][:40]))
    if not live:
        print('  NO LIVE CASES -- this suite would pass against anything')
        ok = False

    print()
    print('BAD read -- the guard must CATCH it')
    bad_rows = build(cases, True)
    caught = True
    for i in live:
        a, b = bad_rows[i]
        if a == b:
            caught = False
            print('  FAIL  %-40s guard agreed on corrupt bytes'
                  % cases[i][0][:40])
    if caught:
        print('  all %d reachable cases rejected the corrupted read' % len(live))
    else:
        ok = False

    print()
    print('VBR GUARD OK' if ok else 'VBR GUARD FAULT')
    return 0 if ok else 1


sys.exit(main())
