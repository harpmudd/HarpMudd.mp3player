#!/usr/bin/env python3
"""A scoreboard for picojpeg: instructions retired, and a checksum of its output.

Album art was measured at 1660 ms for a 500x500 cover and 4717 ms for a
1200x1190 one, and a two-term fit over four hardware measurements (validated to
1.3% on a held-out point) attributes that to:

    ~9.8 us per entropy byte        ~4.5 us per decoded pixel

For the big covers that is 98% entropy decoding, and picojpeg reads it ONE BIT
AT A TIME through a 16-bit buffer -- it is written for AVR-class parts with
2 KB of RAM, not for speed. Making that faster is the single biggest available
win, and it is a hot path where a mistake means silently wrong artwork.

So: measure before changing, and gate on the output not moving.

    python tools/host/jpeg_bench.py <file> --save      # record a baseline
    python tools/host/jpeg_bench.py <file>             # compare against it

<file> may be a .jpg, or a .flac/.mp3 whose embedded picture is extracted.

The PRIMARY gate is the checksum, and it is deliberately a self-comparison
rather than a check against a reference decoder: picojpeg's IDCT is an
approximation and will never match libjpeg bit for bit, so a tolerance against
Pillow could not tell a 2x speedup that is correct from one that is subtly
wrong. An optimisation must leave every decoded byte identical, and that is
exactly what an unchanged checksum proves.

`--verify` additionally decodes with Pillow and reports mean absolute error,
which is a sanity check on the BASELINE being right in the first place. It is
expected to be small but non-zero.

The JPEG is passed to the simulator as a blob rather than compiled in as a C
array: a 470 KB cover would otherwise be a 2 MB source file.
"""
import io
import json
import os
import struct
import subprocess
import sys

STATS = [False]
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
BASELINE = os.path.join(HERE, 'jpeg_bench_baseline.json')
ART_IMG = 92                      # matches fw/art.inc


def flac_pic(path):
    with open(path, 'rb') as f:
        if f.read(4) != b'fLaC':
            return None
        while True:
            h = f.read(4)
            if len(h) < 4:
                return None
            last, t = h[0] & 0x80, h[0] & 0x7F
            b = f.read((h[1] << 16) | (h[2] << 8) | h[3])
            if t == 6:
                q = 4
                q += 4 + struct.unpack('>I', b[q:q + 4])[0]
                q += 4 + struct.unpack('>I', b[q:q + 4])[0] + 16
                n = struct.unpack('>I', b[q:q + 4])[0]
                return b[q + 4:q + 4 + n]
            if last:
                return None


def mp3_pic(path):
    with open(path, 'rb') as f:
        h = f.read(10)
        if h[:3] != b'ID3':
            return None
        tag = f.read((h[6] << 21) | (h[7] << 14) | (h[8] << 7) | h[9])
    i = 0
    while i + 10 <= len(tag):
        fid = tag[i:i + 4]
        if not fid.strip(b'\0'):
            break
        b4 = tag[i + 4:i + 8]
        n = ((b4[0] << 21) | (b4[1] << 14) | (b4[2] << 7) | b4[3]) \
            if h[3] >= 4 else struct.unpack('>I', b4)[0]
        if fid == b'APIC':
            j = tag[i + 10:i + 10 + n].find(b'\xff\xd8\xff')
            if j >= 0:
                return tag[i + 10 + j:i + 10 + n]
        i += 10 + n
    return None


def load(path):
    ext = os.path.splitext(path)[1].lower()
    if ext == '.flac':
        return flac_pic(path)
    if ext == '.mp3':
        return mp3_pic(path)
    with open(path, 'rb') as f:
        return f.read()


GEN = r'''
/* GENERATED by jpeg_bench.py. Decodes the blob and reports instructions and a
 * checksum over every byte picojpeg produces. */
#include "hostio.h"
#include "picojpeg.h"

#define INSTR (*(volatile uint32_t *)0xF0000020u)

static unsigned char jpg[%(CAP)du];
static unsigned int  jlen, jpos;

static unsigned char feed(unsigned char *pBuf, unsigned char n,
                          unsigned char *pRead, void *pData)
{
    (void)pData;
    unsigned int k = jlen - jpos;
    if (k > n) k = n;
    for (unsigned int i = 0; i < k; i++) pBuf[i] = jpg[jpos + i];
    jpos += k;
    *pRead = (unsigned char)k;
    return 0;
}

int main(void)
{
    /* Pull the image in over the blob DMA before timing starts. */
    MMIO_DST = (uint32_t)(uintptr_t)jpg;
    MMIO_SRC = 0;
    MMIO_LEN = MMIO_SIZE;
    jlen = MMIO_LEN;
    jpos = 0;

    pjpeg_image_info_t info;
    uint32_t t0 = INSTR;
    unsigned char st = pjpeg_decode_init(&info, feed, 0, %(REDUCE)d);
    if (st) { hputs("ERR "); hputu(st); hnl(); return 0; }

    /* FNV-1a over every decoded byte, in decode order. Any change in the
     * entropy path, the IDCT or the colour conversion moves this. */
    uint32_t hsh = 2166136261u, mcus = 0;
    for (;;) {
        unsigned char e = pjpeg_decode_mcu();
        if (e) break;
        mcus++;
        uint32_t n = (uint32_t)info.m_MCUWidth * info.m_MCUHeight;
        for (uint32_t i = 0; i < n; i++) {
            hsh = (hsh ^ info.m_pMCUBufR[i]) * 16777619u;
            hsh = (hsh ^ info.m_pMCUBufG[i]) * 16777619u;
            hsh = (hsh ^ info.m_pMCUBufB[i]) * 16777619u;
        }
    }
    uint32_t t1 = INSTR;

#if PJPG_STATS
    {
        extern unsigned long gStatFast, gStatSlow, gStatLen[18];
        unsigned int k;
        hputs("STATS ");
        hputu((unsigned)gStatFast); hputc(32);
        hputu((unsigned)gStatSlow);
        for (k = 1; k <= 16u; k++) { hputc(32); hputu((unsigned)gStatLen[k]); }
        hnl();
    }
#endif
    hputu(t1 - t0);                  hputc(32);
    hputu(hsh);                      hputc(32);
    hputu((unsigned)info.m_width);   hputc(32);
    hputu((unsigned)info.m_height);  hputc(32);
    hputu(mcus);                     hnl();
    return 0;
}
'''


def run(jpg, reduce_flag):
    blob = os.path.join(HERE, 'jpeg_bench.bin')
    with open(blob, 'wb') as f:
        f.write(jpg)

    gen = os.path.join(HERE, 'jpeg_bench_gen.c')
    with io.open(gen, 'w', encoding='utf-8', newline='\n') as f:
        f.write(GEN % {'CAP': len(jpg) + 16, 'REDUCE': reduce_flag})

    gcc = os.path.join(ROOT, 'toolchain',
                       'xpack-riscv-none-elf-gcc-15.2.0-1', 'bin',
                       'riscv-none-elf-gcc.exe')
    elf = os.path.join(HERE, 'jpeg_bench.elf')
    cflags = ['-DPJPG_STATS=1'] if STATS[0] else []
    r = subprocess.run([gcc, '-march=rv32im', '-mabi=ilp32', '-mno-relax',
                        '-Os', '-ffreestanding', '-nostdlib', '-nostartfiles'] + cflags + [
                        '-I', os.path.join(ROOT, 'third_party', 'picojpeg'),
                        '-I', HERE,
                        '-T', os.path.join(HERE, 'link.ld'), '-o', elf,
                        os.path.join(HERE, 'start.S'), gen,
                        os.path.join(ROOT, 'third_party', 'picojpeg',
                                     'picojpeg.c'),
                        '-lgcc'], capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[:2000])
        raise SystemExit(2)

    out = subprocess.run([sys.executable,
                          os.path.join(ROOT, 'tools', 'rv32sim.py'), elf, blob],
                         capture_output=True, text=True)
    if out.returncode:
        print(out.stderr[:2000])
        raise SystemExit(2)
    stats = None
    lines = [l for l in out.stdout.splitlines() if l.strip()]
    if lines and lines[0].startswith('STATS'):
        f = lines[0].split()
        stats = dict(fast=int(f[1]), slow=int(f[2]),
                     hist=[int(x) for x in f[3:19]])
        lines = lines[1:]
    out_stdout = lines[0] if lines else ''
    row = out_stdout.split()
    if not row or row[0] == 'ERR':
        print('decode failed: %s' % ' '.join(row))
        raise SystemExit(1)
    return dict(instr=int(row[0]), hash=int(row[1]),
                w=int(row[2]), h=int(row[3]), mcus=int(row[4]), stats=stats)


def pillow_mae(jpg, r):
    try:
        from PIL import Image
    except ImportError:
        return None
    try:
        im = Image.open(io.BytesIO(jpg)).convert('RGB')
    except Exception:
        return None
    # Only a coarse sanity figure: picojpeg's IDCT is an approximation, so a
    # small non-zero error is the EXPECTED result, not a failure.
    im = im.resize((ART_IMG, ART_IMG))
    px = list(im.getdata())
    return sum(sum(p) for p in px) / float(len(px) * 3)


def main(argv):
    if not argv:
        print(__doc__)
        return 2
    path = argv[0]
    save = '--save' in argv
    verify = '--verify' in argv
    STATS[0] = '--stats' in argv

    jpg = load(path)
    if not jpg:
        print('no image in %s' % path)
        return 2

    # The core takes the cheap 1/8 path only when it still lands at or above
    # the panel on both axes -- mirror that choice so the number means what the
    # hardware does. See art_decode() in fw/art.inc.
    probe = run(jpg, 1)
    reduce_flag = 1 if ((probe['w'] + 7) // 8 >= ART_IMG and
                        (probe['h'] + 7) // 8 >= ART_IMG) else 0
    res = probe if reduce_flag else run(jpg, 0)

    name = os.path.basename(path)
    print('%s' % name)
    print('  %dx%d, %d bytes, path %s, %d MCUs'
          % (res['w'], res['h'], len(jpg),
             'reduce 1/8' if reduce_flag else 'FULL', res['mcus']))
    print('  instructions : %s' % format(res['instr'], ','))
    print('  output hash  : %08X' % res['hash'])
    if res.get('stats'):
        st = res['stats']
        tot = st['fast'] + st['slow']
        print('  lookahead    : %s hit, %s miss  (%.1f%% hit)'
              % (format(st['fast'], ','), format(st['slow'], ','),
                 100.0 * st['fast'] / tot if tot else 0))
        print('  code lengths : ' + '  '.join(
            '%d:%.1f%%' % (i + 1, 100.0 * n / tot)
            for i, n in enumerate(st['hist']) if n and 100.0 * n / tot >= 0.5))
        over = sum(st['hist'][8:])
        print('  >8 bits      : %.1f%%   (what a wider table could reach)'
              % (100.0 * over / tot if tot else 0))

    if verify:
        mae = pillow_mae(jpg, res)
        print('  pillow mean  : %s' % ('%.1f' % mae if mae else 'unavailable'))

    db = {}
    if os.path.exists(BASELINE):
        db = json.load(open(BASELINE))
    key = '%s|%s' % (name, 'r' if reduce_flag else 'f')

    if save:
        db[key] = {'instr': res['instr'], 'hash': res['hash']}
        json.dump(db, open(BASELINE, 'w'), indent=1, sort_keys=True)
        print('  baseline saved')
        return 0

    if key not in db:
        print('  no baseline -- run with --save first')
        return 0

    b = db[key]
    print()
    if res['hash'] != b['hash']:
        print('  OUTPUT CHANGED  %08X -> %08X' % (b['hash'], res['hash']))
        print('  REJECT: an optimisation must leave every decoded byte alone.')
        return 1
    d = b['instr'] - res['instr']
    print('  output identical (%08X)' % res['hash'])
    print('  instructions %s -> %s  (%+.1f%%, %.2fx)'
          % (format(b['instr'], ','), format(res['instr'], ','),
             -100.0 * d / b['instr'], b['instr'] / float(res['instr'])))
    return 0


sys.exit(main(sys.argv[1:]))
