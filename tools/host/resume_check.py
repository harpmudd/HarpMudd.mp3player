#!/usr/bin/env python3
"""Checks that a resume point survives RS_PACK -> RS_TRACK for every track.

The track index is split across the packed word -- the low 7 bits where they
have always been, and the 8th in bit 25. Reader and writer each look correct
in isolation, which is exactly how the field came to be widened on the READ
side only: RS_TRACK gained the 8th bit, RS_PACK never wrote it, and resuming
track 200 of a long playlist silently returned track 72. Nothing caught it
because both halves read as right on their own.

So this round-trips EVERY index the firmware can hold, not a sample, and it
checks the other two fields come back intact at the same time -- a widened
track field that stole a bit from the seconds would be the next version of
the same bug.

It also checks BACKWARD COMPATIBILITY, which is the reason the field was
split rather than moved: a word written by the old 7-bit packer has bit 25
clear and must still read back as 0..127.

The C is not re-implemented here. The macros are EXTRACTED from fw/player.c
and compiled, so the thing under test is the shipping source, and it runs
under tools/rv32sim.py -- same 32-bit wrapping as the target.

    python tools/host/resume_check.py
"""
import io
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))

PL_MAX = 256            # fw/player.c -- the range that must survive
SECS = 12345            # arbitrary, inside the 17-bit field
MAXSECS = 0x1FFFF


def extract_define(src, name):
    """Pull one #define out, following backslash continuations."""
    m = re.search(r'^#define\s+%s\b' % re.escape(name), src, re.M)
    if not m:
        raise SystemExit('no #define %s in fw/player.c' % name)
    out, i = [], m.start()
    for line in src[i:].split('\n'):
        out.append(line)
        if not line.rstrip().endswith('\\'):
            break
    return '\n'.join(out)


def main():
    src = io.open(os.path.join(ROOT, 'fw', 'player.c'), encoding='utf-8').read()
    macros = '\n'.join(extract_define(src, n)
                       for n in ('RS_TRACK', 'RS_SECS', 'RS_PL', 'RS_PACK'))

    gen = os.path.join(HERE, 'resume_gen.c')
    with io.open(gen, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* GENERATED by resume_check.py from fw/player.c. '
                'Do not edit. */\n')
        f.write('#include "hostio.h"\n\n')
        f.write(macros + '\n\n')
        f.write('int main(void)\n{\n')
        f.write('    unsigned t;\n')
        # 1. round trip every index, and the other fields with it
        f.write('    for (t = 0; t < %du; t++) {\n' % PL_MAX)
        f.write('        unsigned w = RS_PACK(t, %du, 1);\n' % SECS)
        f.write('        hputu(RS_TRACK(w)); hnl();\n')
        f.write('        hputu(RS_SECS(w));  hnl();\n')
        f.write('        hputu(RS_PL(w));    hnl();\n')
        f.write('    }\n')
        # 2. a word from the OLD 7-bit packer must still read back
        f.write('    for (t = 0; t < 128u; t++) {\n')
        f.write('        unsigned old = (t & 0x7Fu) | (%du << 7) | (1u << 24);\n'
                % SECS)
        f.write('        hputu(RS_TRACK(old)); hnl();\n')
        f.write('    }\n')
        # 3. the seconds field at its limit, with the top track index
        f.write('    hputu(RS_SECS(RS_PACK(255u, %du, 1))); hnl();\n' % MAXSECS)
        f.write('    hputu(RS_TRACK(RS_PACK(255u, %du, 1))); hnl();\n' % MAXSECS)
        # 4. bit 31 must stay clear -- APF stores these signed
        f.write('    hputu((RS_PACK(255u, %du, 1) >> 31) & 1u); hnl();\n' % MAXSECS)
        f.write('    return 0;\n}\n')

    gcc = os.path.join(ROOT, 'toolchain',
                       'xpack-riscv-none-elf-gcc-15.2.0-1', 'bin',
                       'riscv-none-elf-gcc.exe')
    elf = os.path.join(HERE, 'resume.elf')
    cmd = [gcc, '-march=rv32im', '-mabi=ilp32', '-mno-relax', '-O2',
           '-ffreestanding', '-nostdlib', '-nostartfiles',
           '-T', os.path.join(HERE, 'link.ld'), '-o', elf,
           os.path.join(HERE, 'start.S'), gen, '-lgcc']
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        print(r.stderr)
        return 2

    out = subprocess.run(
        [sys.executable, os.path.join(ROOT, 'tools', 'rv32sim.py'), elf],
        capture_output=True, text=True)
    got = [int(x) for x in out.stdout.split()]
    want_n = PL_MAX * 3 + 128 + 3
    if len(got) != want_n:
        print('expected %d values, got %d\n%s%s'
              % (want_n, len(got), out.stdout, out.stderr))
        return 2

    bad = []
    # 1. round trip
    for t in range(PL_MAX):
        tr, sc, pl = got[t * 3], got[t * 3 + 1], got[t * 3 + 2]
        if tr != t:
            bad.append('track %d came back as %d' % (t, tr))
        if sc != SECS:
            bad.append('track %d: seconds %d, want %d' % (t, sc, SECS))
        if pl != 1:
            bad.append('track %d: playlist flag %d, want 1' % (t, pl))
    # 2. old words
    base = PL_MAX * 3
    for t in range(128):
        if got[base + t] != t:
            bad.append('OLD-format word for track %d read back as %d'
                       % (t, got[base + t]))
    # 3/4. limits
    tail = got[base + 128:]
    if tail[0] != MAXSECS:
        bad.append('seconds at limit: %d, want %d' % (tail[0], MAXSECS))
    if tail[1] != 255:
        bad.append('track 255 at second limit: %d' % tail[1])
    if tail[2] != 0:
        bad.append('bit 31 set -- APF stores these SIGNED')

    print('round trip      : %d indices 0..%d' % (PL_MAX, PL_MAX - 1))
    print('old-format read : 128 words from the 7-bit packer')
    print('field limits    : seconds 0x%X, track 255, bit 31 clear' % MAXSECS)
    print()
    if bad:
        print('FAIL -- %d problem(s):' % len(bad))
        for b in bad[:12]:
            print('  ' + b)
        if len(bad) > 12:
            print('  ... and %d more' % (len(bad) - 12))
        return 1
    print('PASS -- every index survives, old words still read, no field collision')
    return 0


if __name__ == '__main__':
    sys.exit(main())
