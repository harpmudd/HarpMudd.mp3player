#!/usr/bin/env python3
"""Runs the SHIPPING pl_extinf() and pl_parse() over playlists of known shape.

Extended .m3u carries "#EXTINF:<seconds>,<title>" ahead of each entry, and that
number is what spares a headerless MP3 the size probe -- so if it is parsed
wrongly the symptom is not a wrong duration, it is the 8 s wait and the stutter
coming back, which costs a hardware round trip to notice.

The C is EXTRACTED from fw/playlist.inc rather than reimplemented, so what is
under test cannot drift from what ships, and it runs under tools/rv32sim.py:
same 32-bit wrapping, same char signedness as the target.

Carries a NEGATIVE CONTROL. Three tests in this project have passed against a
deliberately broken implementation -- empty USLT descriptors, a corpus read off
an absent SD card, zero resumes fired. So this one breaks the parser on purpose
and fails if the suite still passes.

    python tools/host/extinf_check.py
"""
import io
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))

# (name, playlist text, [(path, expected secs), ...])
CASES = [
    ('plain, no EXTINF at all',
     'a.mp3\nb.mp3\n',
     [('a.mp3', 0), ('b.mp3', 0)]),

    ('extended, every entry labelled',
     '#EXTM3U\n#EXTINF:367,One\na.mp3\n#EXTINF:508,Two\nb.mp3\n',
     [('a.mp3', 367), ('b.mp3', 508)]),

    ('mixed: only the second is labelled',
     'a.mp3\n#EXTINF:42,Two\nb.mp3\n',
     [('a.mp3', 0), ('b.mp3', 42)]),

    ('-1 means unknown, not minus one',
     '#EXTINF:-1,Unknown\na.mp3\n',
     [('a.mp3', 0)]),

    ('fractional seconds truncate',
     '#EXTINF:367.5,Frac\na.mp3\n',
     [('a.mp3', 367)]),

    ('absurd value rejected rather than wrapped',
     '#EXTINF:99999999,Huge\na.mp3\n',
     [('a.mp3', 0)]),

    ('a comment between EXTINF and its entry',
     '#EXTINF:120,One\n# hand-written note\na.mp3\n',
     [('a.mp3', 120)]),

    ('EXTINF with no entry after it is dropped',
     '#EXTINF:120,One\na.mp3\n#EXTINF:999,Dangling\n',
     [('a.mp3', 120)]),

    ('two EXTINF in a row: the last one wins',
     '#EXTINF:11,A\n#EXTINF:22,B\na.mp3\n',
     [('a.mp3', 22)]),

    ('CRLF endings, as a Windows editor saves',
     '#EXTM3U\r\n#EXTINF:367,One\r\na.mp3\r\n#EXTINF:508,Two\r\nb.mp3\r\n',
     [('a.mp3', 367), ('b.mp3', 508)]),

    ('UTF-8 BOM ahead of everything',
     '﻿#EXTINF:367,One\na.mp3\n',
     [('a.mp3', 367)]),

    ('near-miss keywords must not match',
     '#EXTINFO:50,x\n#EXTINF 60,x\n#extinf:70,x\na.mp3\n',
     [('a.mp3', 0)]),

    ('no seconds at all after the colon',
     '#EXTINF:,Nothing\na.mp3\n',
     [('a.mp3', 0)]),

    ('the shipped default: comment header, plain entries',
     '# Default playlist.\n# Lines starting with # are ignored.\na.mp3\nb.mp3\n',
     [('a.mp3', 0), ('b.mp3', 0)]),
]


def extract(src, sig):
    """Pull one function out of the firmware source, brace-balanced."""
    i = src.index(sig)
    j = src.index('{', i)
    depth = 0
    for k in range(j, len(src)):
        if src[k] == '{':
            depth += 1
        elif src[k] == '}':
            depth -= 1
            if depth == 0:
                return src[i:k + 1]
    raise SystemExit('unbalanced braces extracting %s' % sig)


def build_and_run(break_it):
    inc = io.open(os.path.join(ROOT, 'fw', 'playlist.inc'),
                  encoding='utf-8').read()
    extinf = extract(inc, 'static uint16_t pl_extinf')
    parse = extract(inc, 'static void pl_parse')

    if break_it:
        # The exact fault this guards against: dropping the held figure instead
        # of attaching it to the entry that follows the EXTINF line.
        before = parse
        parse = parse.replace('pl_secs[pl_count] = pend;',
                              'pl_secs[pl_count] = 0;')
        if parse == before:
            raise SystemExit('negative control could not find its target -- '
                             'pl_parse changed shape, fix this test')

    gen = os.path.join(HERE, 'extinf_gen.c')
    with io.open(gen, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* GENERATED by extinf_check.py from fw/playlist.inc. */\n')
        f.write('#include "hostio.h"\n\n')
        f.write('#define PL_MAX      256u\n')
        f.write('#define PL_TEXT_MAX 12288u\n\n')
        f.write('static char     pl_text[PL_TEXT_MAX];\n')
        f.write('static uint16_t pl_off[PL_MAX];\n')
        f.write('static uint16_t pl_secs[PL_MAX];\n')
        f.write('static uint16_t pl_count;\n')
        f.write('static uint8_t  pl_truncated;\n')
        f.write('static char plt_get(uint32_t i) { return pl_text[i]; }\n')
        f.write('static void plt_set(uint32_t i, char c) { pl_text[i] = c; }\n\n')
        f.write(extinf + '\n\n')
        f.write(parse + '\n\n')

        for ci, (_, text, _) in enumerate(CASES):
            raw = text.encode('utf-8')
            f.write('static const unsigned char T%d[] = {%s};\n'
                    % (ci, ','.join(str(b) for b in raw)))
            f.write('#define L%d %du\n' % (ci, len(raw)))

        f.write('\nint main(void)\n{\n')
        for ci, _ in enumerate(CASES):
            f.write('    {\n')
            f.write('        for (uint32_t k = 0; k < L%d; k++)\n' % ci)
            f.write('            pl_text[k] = (char)T%d[k];\n' % ci)
            f.write('        pl_text[L%d] = 0;\n' % ci)
            f.write('        pl_truncated = 0;\n')
            f.write('        pl_parse(L%d);\n' % ci)
            f.write('        hputu(pl_count);\n')
            f.write('        for (uint32_t k = 0; k < pl_count; k++) {\n')
            f.write('            hputc(32); hputu(pl_secs[k]); hputc(47);\n')
            f.write('            const char *nm = pl_text + pl_off[k];\n')
            f.write('            while (*nm) { hputc(*nm); nm++; }\n')
            f.write('        }\n')
            f.write('        hnl();\n')
            f.write('    }\n')
        f.write('    return 0;\n}\n')

    gcc = os.path.join(ROOT, 'toolchain',
                       'xpack-riscv-none-elf-gcc-15.2.0-1', 'bin',
                       'riscv-none-elf-gcc.exe')
    elf = os.path.join(HERE, 'extinf.elf')
    r = subprocess.run([gcc, '-march=rv32im', '-mabi=ilp32', '-mno-relax',
                        '-O2', '-ffreestanding', '-nostdlib', '-nostartfiles',
                        '-T', os.path.join(HERE, 'link.ld'), '-o', elf,
                        os.path.join(HERE, 'start.S'), gen, '-lgcc'],
                       capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[:2000])
        raise SystemExit(2)

    out = subprocess.run([sys.executable,
                          os.path.join(ROOT, 'tools', 'rv32sim.py'), elf],
                         capture_output=True, text=True)
    if out.returncode:
        print(out.stderr[:2000])
        raise SystemExit(2)
    return [l for l in out.stdout.splitlines() if l.strip()]


def check(rows, verbose):
    ok = True
    for ci, (name, _, want) in enumerate(CASES):
        got = []
        if ci < len(rows):
            for tok in rows[ci].split()[1:]:
                secs, _, path = tok.partition('/')
                got.append((path, int(secs)))
        good = (got == want)
        if not good:
            ok = False
        if verbose:
            print('  %-5s %s' % ('ok' if good else 'FAIL', name))
            if not good:
                print('          want %s' % want)
                print('          got  %s' % got)
    return ok


def main():
    print('pl_extinf / pl_parse, %d cases' % len(CASES))
    real = check(build_and_run(False), True)
    broken = check(build_and_run(True), False)
    print()
    print('negative control: broken parser %s'
          % ('STILL PASSES -- this suite proves nothing' if broken
             else 'is caught'))
    print()
    good = real and not broken
    print('EXTINF OK' if good else 'EXTINF FAULT')
    return 0 if good else 1


sys.exit(main())
