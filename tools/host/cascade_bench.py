#!/usr/bin/env python3
"""Measures the octave cascade, with the loop LIFTED from fw/player.c.

The cascade runs 8 one-pole stages over the PCM feed to drive the 16-band
spectrum meter and the cassette. Measured on hardware 2026-09-22 it costs about
6% of the CPU: the MP3 control read D6 with the cassette showing and D12 on
bars, and that 6% is exactly the margin the demanding FLAC files are short of.

The cassette reads only spec_lvl[8]/[9] (stage 4, the shell rim) and
spec_lvl[14]/[15] (stage 7, the bass glow), so the split and the two
accumulates are waste for the other six stages -- including stage 0, which is
the one that runs on every sample. This reports what that waste costs by
compiling the SAME loop text three ways.

The loop is EXTRACTED rather than retyped, so the benchmark cannot drift away
from what ships. Decimating the input was the obvious alternative and is the
wrong answer: every stage's corner frequency scales with the rate it is fed at,
so a decimated cascade moves all 16 bands down an octave and aliases the top.

    python tools/host/cascade_bench.py
"""
import io
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
GCC = os.path.join(ROOT, 'toolchain', 'xpack-riscv-none-elf-gcc-15.2.0-1',
                   'bin', 'riscv-none-elf-gcc.exe')

HEADER = '''/* GENERATED by tools/host/cascade_bench.py. Do not edit.
 * The loop below is lifted VERBATIM from fw/player.c. */
#include "hostio.h"

#define SPEC_OCT   8u
#define SPEC_BANDS (SPEC_OCT * 2u)
#define SPEC_SH    1u
#define SPEC_SH2   2u
#define SPEC_TAPE_STAGES ((1u << 4) | (1u << 7))

static int32_t  spec_lp[SPEC_OCT], spec_slp[SPEC_OCT];
static uint32_t spec_cnt[SPEC_OCT];
static uint32_t spec_acc[SPEC_BANDS];
static int16_t  pcm[2304];

int main(void)
{
    uint32_t seed = 12345u;
    const uint32_t need = NEED_MASK;
    int stereo = 1;
    /* 38 x 1152 stereo frames ~= one second at 44.1 kHz, fed in the same
     * 1152-pair blocks meters_feed() really gets. */
    for (uint32_t blk = 0; blk < 38u; blk++) {
        int n = 1152 * 2;
        for (int k = 0; k < n; k++) {
            seed = seed * 1103515245u + 12345u;
            pcm[k] = (int16_t)((int32_t)(seed >> 16) - 32768);
        }
'''

FOOTER = '''
    }
    /* Consume the accumulators so none of it is optimised away. */
    uint32_t sum = 0;
    for (uint32_t b = 0; b < SPEC_BANDS; b++) sum += spec_acc[b];
    hputs("acc "); hputu(sum); hputc(10);
    MMIO_EXIT = 0;
    return 0;
}
'''


def extract_loop():
    src = io.open(os.path.join(ROOT, 'fw', 'player.c'), encoding='utf-8').read()
    i = src.index('const uint32_t need = (viz_mode == VIZ_LED)')
    i = src.index('for (int i = 0; i < n; i += (stereo ? 2 : 1)) {', i)
    j = src.index('spec_n += (uint32_t)(stereo ? (n / 2) : n);', i)
    return '            ' + src[i:j].strip()


def run(label, mask, gen):
    elf = os.path.join(HERE, 'casc.elf')
    r = subprocess.run([GCC, '-march=rv32im', '-mabi=ilp32', '-mno-relax',
                        '-O2', '-ffreestanding', '-nostdlib',
                        '-DNEED_MASK=' + mask,
                        '-T', os.path.join(HERE, 'link.ld'),
                        os.path.join(HERE, 'start.S'), gen, '-o', elf],
                       capture_output=True, text=True)
    if r.returncode:
        print(r.stdout + r.stderr)
        raise SystemExit('compile failed: ' + label)
    sim = subprocess.run([sys.executable,
                          os.path.join(ROOT, 'tools', 'rv32sim.py'), elf],
                         capture_output=True, text=True)
    m = re.search(r'\[([0-9,]+) instructions', sim.stderr)
    if not m:
        print(sim.stdout + sim.stderr)
        raise SystemExit('no instruction count: ' + label)
    n = int(m.group(1).replace(',', ''))
    print('  %-28s %12s instructions / second of audio' % (label, format(n, ',')))
    return n


def main():
    gen = os.path.join(HERE, 'cascade_bench.c')
    io.open(gen, 'w', encoding='utf-8', newline='\n').write(
        HEADER + extract_loop() + FOOTER)

    led = run('spectrum, all 16 bands', '0xFFu', gen)
    tape = run('cassette, stages 4 and 7', 'SPEC_TAPE_STAGES', gen)
    floor = run('floor: LP chain only', '0u', gen)

    print('')
    print('  band work, all 16 stages : %12s' % format(led - floor, ','))
    print('  band work, 2 stages      : %12s' % format(tape - floor, ','))
    print('  saved by the gate        : %12s   (%.0f%% of the band work)'
          % (format(led - tape, ','), 100.0 * (led - tape) / (led - floor)))
    print('')
    print('  The LP chain is %s of it and is IRREDUCIBLE: stage 7 cannot be'
          % format(floor, ','))
    print('  reached without stages 0-6 having run. So this recovers about HALF')
    print('  of the cassette\'s measured cost, not all of it. Going further means')
    print('  giving the cassette its own two-pole envelope instead of the chain.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
